// Проверки полей черновика до отправки (текст ошибки или null)
const isNum = (v) => typeof v === 'number' && Number.isFinite(v);
export const validateText = (v) => (v ? null : 'Поле не может быть пустым.');
export const validateShare = (v) => {
  if (!isNum(v)) return 'Укажите число, например 0,25.';
  return v > 0 && v <= 1 ? null : 'Доля — число больше 0 и не больше 1.';
};
export const validateBaseShare = (v) => {
  if (!isNum(v)) return 'Укажите число, например 0,5.';
  return v >= 0 && v <= 1 ? null : 'Доля базы — число от 0 до 1.';
};
export const validatePositiveInt = (v) =>
  (isNum(v) && Number.isInteger(v) && v > 0 ? null : 'Целое число больше 0.');
export const validateRotation = (v) =>
  (isNum(v) && v >= 1 ? null : 'Коэффициент ротации — число не меньше 1.');
export const validateYear = (v) =>
  (isNum(v) && Number.isInteger(v) && v >= 2000 && v <= 2100 ? null : 'Год от 2000 до 2100.');

