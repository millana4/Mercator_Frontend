// Склонение по числу: forms = [для 1, для 2-4, для 5+], например ['нишу', 'ниши', 'ниш']
const plural = (n, [one, few, many]) => {
  const n10 = n % 10;
  const n100 = n % 100;
  if (n10 === 1 && n100 !== 11) return one;
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return few;
  return many;
};

// limits - ответ /niches/limits: { used, limit }; лимит задаётся в policies.py аналитики
export const nicheLimitText = ({ used, limit }) => {
  const head = `Вы можете отслеживать до ${limit} ${plural(limit, ['ниши', 'ниш', 'ниш'])}.`;
  const left = Math.max(0, limit - used);
  if (left === 0) {
    return `${head} Лимит исчерпан: чтобы добавить новую нишу, удалите одну из своих.`;
  }
  return `${head} Сейчас можете добавить в отслеживание ещё ${left} `
    + `${plural(left, ['нишу', 'ниши', 'ниш'])}.`;
};

